// Куда ведёт запись на разбор. Единственное место в проекте, где это записано.
//
// Телеграм — основной канал: запись и отправка ссылки на месяц становятся
// одним жестом. Пока имя не подтверждено владельцем, кнопка ведёт на сайт:
// ссылка в никуда хуже лишнего шага, а придуманный ник — хуже обоих,
// потому что открывает чужую переписку.
//
// Подставить имя (без «@») — и кнопка сама переключится на телеграм.

export const CONTACT = {
  telegram: '',
  site: 'https://runscale.ru',
}

/** Ссылка записи и то, как она подписана. Текст кнопки от канала не зависит. */
export function bookingLink() {
  return CONTACT.telegram
    ? { url: `https://t.me/${CONTACT.telegram}`, kind: 'telegram' }
    : { url: CONTACT.site, kind: 'site' }
}
