// Форма недели — веса дней Пн..Вс. Ими разносится хвост плана: день недели
// не равен дню недели, и план на субботу не может совпадать с планом на вторник.
//
// Статус этих чисел важнее самих чисел:
//   'preset' — отраслевое допущение, взято не из данных пользователя;
//   'user'   — пользователь поправил руками, это его решение, тоже допущение;
//   'data'   — пересчитано из его же выручки, когда каждый день недели
//              встретился в ней достаточно раз. Только здесь «посчитано».
//
// Стартуем на нейтральных весах: приписать человеку отрасль, которую он не
// называл, значит начать знакомство с допущения, выданного за знание.

// Плоская неделя. Оставлена как выбор для того, у кого выручка действительно
// ровная (склад, подписка, B2B-отгрузки), но по умолчанию не ставится:
// см. DEFAULT ниже.
export const NEUTRAL = [1, 1, 1, 1, 1, 1, 1]

// Форма по умолчанию. Ровная неделя не бывает ни у кого, кто торгует людям:
// понедельник почти всегда слабее среды, а суббота сильнее вторника. Ставить
// всем единицы значит утверждать про бизнес то, чего не бывает, — и человек
// видит требование на субботу, равное требованию на понедельник, с первого
// экрана. Эти веса — усреднение по рознице, услугам и общепиту: плюс-минус
// верны почти для всех и подписаны допущением, пока не пересчитаны по данным.
export const DEFAULT = [0.85, 0.9, 0.95, 1.0, 1.2, 1.15, 0.95]

