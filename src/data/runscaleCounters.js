/**
 * Последняя оценка ряда — та же величина, что стоит в плитке песочницы.
 * Правый край графика и есть сегодня, и число рядом с графиком обязано
 * совпадать с его последней точкой: среднее рядом с растущей линией читалось
 * бы как «сейчас столько», а это неправда.
 */
export function scoreNow(values) {
  if (!Array.isArray(values) || values.length === 0) return null
  return Math.round(values[values.length - 1] * 10) / 10
}
