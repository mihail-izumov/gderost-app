  // со шкалой, а не со стрелкой: «4» и «БИЗНЕСЫ НА ТРЕКЕ» читаются как
  // показание и его название, не как словосочетание. Поэтому склонения
  // здесь нет и `plural` этому полю не нужен.
  //
  // «Треке» с прописной: это имя продукта и трасса, а не контейнер.
  // Регистр совпадает во всех текстах входа.
