// Счётчики работающей системы: сколько осмотров, сигналов и живых разборов
// она выдала. Это не витринная цифра, а доказательство, что за приложением
// стоит система, которая работает каждый день.
//
// Числа обновляются вручную и здесь, в одном месте. Дата среза едет вместе
// с ними и показывается рядом всегда: счётчик без даты — первое место,
// где мы соврём, потому что вчерашнее число выглядит как сегодняшнее.

// Подпись склоняется по числу, которое стоит над ней: 1 чекап · 2 чекапа ·
// 59 чекапов. Форма выбирается в компоненте функцией `plural` — той же, что
// склоняет дни во всём приложении. Три формы задаются здесь, рядом с числом,
// чтобы новый счётчик заводился одной строкой и не искал себе словарь.
/**
 * Единственное число витрины: сколько бизнесов ведут месяц на Треке.
 *
 * Считается бизнес, внёсший хотя бы один день в этом месяце. Определение
 * проверяемо, и это ровно то, что продукт делает.
 *
 * Почему оно не из `COUNTERS` ниже. Проверки, сигналы и разборы меряют работу
 * Ранскейла — это портфолио, и от прихода человека оно не растёт. Число
 * на входе обязано расти само, иначе витрина показывает чужую заслугу.
 *
 * Парки сети считаются здесь наравне с остальными: метод один, данные одного
 * рода, граница проходит по факту ввода дня, а не по продукту.
 *
 * `asOf` обязателен, пока телеметрия не считает это сама. Дата стоит внутри
 * шторки «Где Рост» — то есть от числа она на один тап, ровно как у счётчиков
 * ниже. Снять её можно только вместе с работающим автообновлением: иначе
 * число становится «со слов» без пометки.
 */
