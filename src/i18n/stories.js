/**
 * Сюжет «Честная цифра». Открывается с плашки кольца и строится от живого
 * состояния: первый слайд — чек-лист четырёх проверок с отметками из петли
 * человека, дальше по слайду на проверку, в порядке загорания. Финал называет
 * ступень, которую приложение не ставит. Продажи в тексте нет: здесь
 * устройство метода, цену и состав человек читает на «Сигналах».
 *
 * Тексты — голос витрины (`docs/контент/ГОЛОС.md`): слова за ужином,
 * показ вместо утверждения, «замер» существительным не печатается.
 *
 * Кольцо стоит на самих слайдах, а не остаётся на плашке за спиной:
 * первый слайд показывает его в состоянии человека, слайды шагов —
 * с указкой на свою дугу (`ring.highlight`, синий цвет активного)
 * и живой строкой ответа под текстом. Связь «дуга — проверка» человек
 * видит, а не вычисляет.
 */
export function honestStory(loop) {
  const full = loop.lit >= loop.segs.length
  const stateRing = {
    segs: loop.segs,
    tone: full ? 'var(--positive)' : 'var(--warning)',
    highlight: null,
  }
  // Указка держит цвет состояния человека: слайды показывают его кольцо,
  // а не схему. Синий здесь был бы третьим состоянием, которого нет.
  const pointerRing = (i) => ({ segs: loop.segs, tone: stateRing.tone, highlight: i })
  const answer = (i) => [{ label: loop.segs[i].check, on: loop.segs[i].on }]
  return [
    {
      id: 'loop',
      kicker: 'Честная цифра',
      title: 'Проверяет за вас',
      text: 'Каждый сегмент — проверка на ваших числах: вместе они не дают месяцу сбиться. Вот ответы прямо сейчас:',
      ring: stateRing,
      checks: loop.segs.map((s) => ({ label: s.check, on: s.on })),
    },
    {
      id: 'data',
      kicker: 'Честная цифра',
      title: 'Первая проверка — ваша',
      text: 'Вы вносите выручку дня — минута вечером. Рядом с каждым числом видно, откуда оно: ввели вы — подписано «со слов».',
      ring: pointerRing(0),
      checks: answer(0),
    },
    {
      id: 'signal',
      kicker: 'Честная цифра',
      title: 'Прогноз готов',
      text: 'Из ваших дней считается прогноз месяца и сколько надо сегодня. Подписано «посчитано»: тап по числу показывает, из чего.',
      ring: pointerRing(1),
      checks: answer(1),
    },
    {
      id: 'action',
      kicker: 'Честная цифра',
      title: 'Работа остаётся за вами',
      text: 'Вы проживаете день, зная свою цифру. Внутрь бизнеса Ранскеил Трек не заглядывает: ваш день он увидит в завтрашней выручке.',
      ring: pointerRing(2),
      checks: answer(2),
    },
    {
      id: 'measure',
      kicker: 'Честная цифра',
      title: 'Ни одного пропуска',
      text: 'Вечером выручка внесена — день закрыт. Пропущенный день гасит сегмент, пока вы его не внесёте.',
      ring: pointerRing(3),
      checks: answer(3),
    },
    {
      id: 'why',
      kicker: 'Честная цифра',
      title: 'Прогноз точнее',
      text: 'Четыре горящих сегмента — прогноз стоит на полных данных. Ступень выше — сверка с кассой: её ставит проверка, не разговор.',
      cta: 'Откуда мои числа',
    },
  ]
}
