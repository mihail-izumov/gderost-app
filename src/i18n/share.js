// Четыре сообщения роста — всё, что уезжает из приложения текстом.
// Меняются здесь; в компонентах эти строки не дублируются.
//
// Замысел: четыре жанра, а не четыре размера одного хвастовства. Сообщение
// утверждает ровно то, что к этому моменту посчитано, и растёт вместе
// с доступной правдой:
//
//   start — заявка на старт: план поставлен, счёт пошёл. Цифр нет вовсе;
//           приземление из одной точки — шум, показать его результатом
//           значит соврать статусом числа;
//   pace  — первый прогноз: три точки, темп перестал скакать от выходного;
//   week  — серия: дисциплина плюс результат, самое сильное из четырёх;
//   month — результат: закрытый факт месяца.
//
// Условия показа живут отдельно — `composables/shareReason.js`, под
// самопроверкой. Здесь только слова и подстановки.
//
// ⚠ Рефрен «Рост не ждёт.» стоит ровно в одном сообщении из четырёх.
// По `brand.js` он живёт на закрытом месяце, стикерах и материалах разбора;
// закрытый месяц — ровно этот случай, в трёх остальных рефрена быть не должно.
//
// ⚠ Ссылка во всех четырёх — короткий адрес, а не упакованный месяц. Это
// приглашение приехать на трек: получателю нужно место, куда встать, а не
// чужая выручка по дням. Отправка своего месяца ссылкой — отдельное действие
// (`ShareMonthButton`), два намерения не смешиваются.

import { BRAND } from './brand.js'
import { monthName, monthOf, daysWord } from './format.js'

/** Старшинство поводов: старший забирает показ. */
export const SHARE_ORDER = ['month', 'week', 'pace', 'start']

// Заголовок шторки. Информирование без объяснения: экран называет состояние,
// а само сообщение стоит ниже целиком.
//
// Заголовок не повторяет первых слов сообщения. «Неделя без пропусков» сверху
// и «Неделя без пропусков» строкой ниже — одна мысль дважды на трёх строках,
// и вторая читается уже как шум.
const HEADS = {
  start: 'Счёт пошёл',
  pace: 'Прогноз появился',
  week: 'Семь дней подряд',
  month: 'Итог месяца',
}

// Тексты. Подстановки в фигурных скобках задания:
//   {месяца} → monthOf · {Месяц} → monthName с прописной
//   {N} → процент целым · {K} → внесено дней · {D} → дней в месяце
const TEXTS = {
  start: (v) => [
    `Поехал. План ${v.monthOf} поставлен, считаю каждый день.`,
    `Давай гонять вместе на ${BRAND.header}.`,
    BRAND.domain,
  ].join('\n'),

  pace: (v) => [
    `Три дня на треке. Прогноз ${v.monthOf} — ${v.N}% плана.`,
    `${BRAND.brandName} считает по дням и врать себе не даёт.`,
    BRAND.domain,
  ].join('\n'),

  week: (v) => [
    `Неделя без пропусков. ${v.K} ${daysWord(v.K)} внесено, прогноз ${v.monthOf} — ${v.N}% плана.`,
    `Давай гонять вместе на ${BRAND.header}.`,
    BRAND.domain,
  ].join('\n'),

  month: (v) => [
    `${v.Month} закрыт: ${v.N}% плана. ${v.K} из ${v.D} дней внесено.`,
    `Считал на ${BRAND.header}. ${BRAND.refrain}`,
    BRAND.domain,
  ].join('\n'),
}

/**
 * Числа сообщения из модели месяца.
 *
 * ⚠ `landPct` брать нельзя: в ядре оно обрезано сверху (`Math.min(100, …)`)
 * — верно для полосы прогресса, где заливка не бывает шире дорожки, и ложь
 * в тексте, который уезжает за пределы приложения. Честные 105 % превратились
 * бы в 100 % ровно в том артефакте, который человек показывает другим.
 * Отношение берётся напрямую и сверху не режется.
 *
 * Закрытый месяц меряется фактом, а не прогнозом: прогнозировать нечего.
 */
function values(reason, m) {
  const T = m && Number(m.T) > 0 ? Number(m.T) : 0
  const ratio = reason === 'month' ? m.realizedRev / T : m.landing / T
  const name = monthName(m.month)
  return {
    monthOf: monthOf(m.month),
    Month: typeof name === 'string' && name ? name[0].toUpperCase() + name.slice(1) : name,
    N: T ? Math.round(ratio * 100) : 0,
    K: m.enteredCount,
    D: m.DIM,
  }
}

/** Заголовок шторки для повода. */
export function shareHead(reason) {
  return HEADS[reason] || ''
}

/** Готовый текст сообщения для повода. Пустая строка — повода нет. */
export function shareText(reason, m) {
  const f = TEXTS[reason]
  if (!f || !m) return ''
  return f(values(reason, m))
}
