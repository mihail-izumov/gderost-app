// Тексты объясняющих мест: анкета подключения, карточка первых шагов,
// окно заявки на подключение бизнеса.
//
// Почему они собраны здесь, а не стоят в компонентах. Эти строки — один
// разговор с человеком, который ещё не понял, что перед ним, и читаются
// они подряд: сюжет входа, анкета, первый экран с пустыми местами. Пока
// каждая фраза жила в своём файле рядом с вёрсткой, сравнить их между собой
// было не с чем, и тон расходился по местам незаметно. Теперь весь разговор
// виден одним файлом, и сверка с описанием текстов идёт машиной.
//
// Подстановки записаны фигурными скобками и заменяются на месте показа:
// строка обязана читаться целиком без вызова функции, иначе сверять её
// с описанием нечем.

/** Подстановка одного значения: `fill('План на {месяц}', '{месяц}', 'август')`. */
export function fill(template, key, value) {
  return String(template).split(key).join(String(value))
}

