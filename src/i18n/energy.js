/**
 * Заперт ли заказ ступени. Замок стоит на заказе, а не на чтении: паспорт
 * открывается целиком у всех. Серия и буткемп ждут состоявшегося разбора,
 * режим — решения по итогу буткемпа, и открыть его нажатием в приложении
 * нельзя.
 *
 * Буткемп заперт до первой встречи по той же причине, что серия: продавать
 * тридцать дней с командой человеку, чьих цифр никто не видел, значит
 * продавать наугад.
 *
 * Живёт здесь, а не в `energyModel`: это правило продажи, а не расчёта.
 */
export function isLocked(id, rated) {
  if (id === 'masterplan' || id === 'bootcamp') return !rated
  if (id === 'runscale') return true
  return false
}

