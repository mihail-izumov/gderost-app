// Правила жеста «потяни-обнови» — чистыми функциями, отдельно от разметки.
//
// Вынесены сюда не ради порядка. Этот жест ломался дважды, и оба раза поломку
// нельзя было увидеть глазами в коде компонента: она жила в одной формуле
// среди обработчиков касания. Теперь правило проверяет машина
// (`scripts/verify-mini.mjs`), и регрессия выпадает до телефона.
//
// ⚠ Две аварии, ради которых всё это написано.
//
// Первая (Н-24). Панель ехала за пальцем по формуле `sqrt(dy) * 9`, то есть
// малое движение УСИЛИВАЛОСЬ, и порог брался на двух сантиметрах. Правило:
// панель обязана ехать медленнее пальца на всём диапазоне.
//
// Вторая (Н-26). Порога по пути оказалось мало. Человек возвращается к верху
// длинной страницы несколькими быстрыми движениями; последнее приходит уже
// на нулевой прокрутке, палец легко проходит триста пикселей — и жест
// срабатывает посреди чтения. Путь не отличает протягивание от рывка,
// поэтому к нему добавлены ещё три условия: прокрутка обязана СТОЯТЬ до
// касания, протягивание обязано длиться, увод вбок отменяет жест.

export const PULL = {
  // Дальше панель не едет: смысл индикатора исчерпан, а тянуть можно бесконечно.
  MAX: 96,
  // Люфт. Пока палец не прошёл столько вниз, прокрутка остаётся прокруткой
  // и `preventDefault` не зовётся: иначе жест отбирает скролл с первого касания.
  SLOP: 12,
  // Гашение. Строго меньше единицы — см. первую аварию.
  DAMP: 0.5,
  // Порог срабатывания по панели. С люфтом это ≈156 px пальца.
  TRIGGER: 72,
  // Столько прокрутка обязана простоять до касания. Инерция iOS шлёт события
  // прокрутки, пока едет, поэтому касание в её конце сюда не попадает.
  SETTLE_MS: 400,
  // Столько длится протягивание. Рывок короче: он летит и кончается.
  HOLD_MS: 260,
  // Увод вбок, после которого жест перестаёт быть вертикальным.
  DRIFT: 40,
}

// Насколько панель уехала за пальцем. Всегда меньше самого движения.
export function pullOffset(dy) {
  if (dy <= PULL.SLOP) return 0
  return Math.min(PULL.MAX, Math.round((dy - PULL.SLOP) * PULL.DAMP))
}

// Может ли жест вообще начаться в момент касания.
export function canStartPull({ scrollTop, sinceScrollMs, busy }) {
  if (busy) return false
  if (scrollTop > 0) return false
  return sinceScrollMs >= PULL.SETTLE_MS
}

// Засчитывается ли отпускание. Порог по панели, длительность против рывка,
// увод вбок против диагонального свайпа.
export function shouldFirePull({ offset, heldMs, drift }) {
  if (offset < PULL.TRIGGER) return false
  if (heldMs < PULL.HOLD_MS) return false
  return Math.abs(drift) <= PULL.DRIFT
}
