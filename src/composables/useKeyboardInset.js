// Сколько экрана съела клавиатура. Одно место на всё приложение.
//
// ⚠ Проблема, ради которой это написано. Шторка стоит `position: fixed`
// у нижнего края, а на iOS клавиатура НЕ двигает нижний край: она рисуется
// поверх страницы. Layout viewport остаётся прежним, шторка честно стоит
// внизу — и оказывается под клавиатурой вместе с полем, в которое человек
// печатает. Он видит цифры только после того, как уберёт клавиатуру.
//
// Что показывает настоящий размер видимой области — `window.visualViewport`.
// Разница между ним и окном и есть высота клавиатуры вместе со служебной
// панелью. Значение кладётся в переменную `--gr-kb` на корне документа,
// и любой прижатый к низу элемент поднимается на неё отступом.
//
// Почему переменная на `:root`, а не проп: слушатель нужен ровно один
// на приложение, а поднимаются от него разные вещи — общая шторка, модалка
// целей, форма ввода. Второй слушатель на второй шторке считал бы то же
// самое ещё раз и расходился бы с первым на кадр.

let started = false

export function startKeyboardInset() {
  if (started || typeof window === 'undefined') return
  const vv = window.visualViewport
  if (!vv) return // Android WebView и старые браузеры: там клавиатура двигает окно сама
  started = true

  const apply = () => {
    // Клавиатура закрывает низ окна. Прокрутка самого visualViewport (когда
    // страница уехала под клавиатуру) вычитается: иначе отступ скачет,
    // пока человек листает содержимое шторки.
    const hidden = Math.max(0, window.innerHeight - vv.height - vv.offsetTop)
    // Мелочь в пару пикселей — это адресная строка, а не клавиатура.
    document.documentElement.style.setProperty('--gr-kb', hidden > 60 ? `${Math.round(hidden)}px` : '0px')
  }

  vv.addEventListener('resize', apply)
  vv.addEventListener('scroll', apply)
  apply()
}
