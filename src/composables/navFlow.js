// Правила навигации — чистыми функциями, отдельно от разметки.
//
// Вынесены сюда по той же причине, что и правила жеста: переходы между
// вкладками и под-страницами ломались дважды, и оба раза поломку нельзя было
// увидеть глазами — она жила в трёх строках внутри обработчика. Человек шёл
// с «Прогресса» в неделю и возвращался на «Сегодня»; шёл с «Сигналов»
// в «Цели и планы» и возвращался туда же. Теперь правило проверяет машина.
//
// Состояние навигации — три величины и ничего больше:
//
//   tab      — активная вкладка
//   subView  — под-страница поверх неё («день», «цели») или пусто
//   homeTab  — вкладка, в которую вернёт «Назад»
//
// Главное правило: под-страница принадлежит тому разделу, ОТКУДА в неё вошли.
// Назначенный владелец («день всегда принадлежит Сегодня») теряет путь: под
// одной и той же под-страницей стоят разные вопросы, и возврат обязан вести
// к тому, который человек задал.

export const SUB_VIEW_IDS = ['day', 'goals']

export const initialNav = () => ({ tab: 'today', subView: '', homeTab: 'today', dayPreset: '' })

/**
 * Переход. `where` — либо вкладка, либо под-страница; `arg` — день строкой
 * или адрес объектом.
 */
export function navigate(nav, where, arg) {
  const t = typeof arg === 'string' ? { day: arg } : (arg || {})
  if (SUB_VIEW_IDS.includes(where)) {
    return {
      // Вкладка не переключается: человек стоит там же, откуда пришёл,
      // и подпись в таб-баре обязана это показывать.
      tab: nav.tab,
      subView: where,
      // Возврат запоминается только на входе снаружи. Переход из одной
      // под-страницы в другую его не переписывает: цепочка «неделя → цели»
      // всё равно кончается там, где началась.
      homeTab: nav.subView ? nav.homeTab : nav.tab,
      dayPreset: where === 'day' && t.day ? t.day : '',
    }
  }
  return { tab: where, subView: '', homeTab: nav.homeTab, dayPreset: '' }
}

/** Возврат с под-страницы. */
export function back(nav) {
  return { tab: nav.homeTab || 'today', subView: '', homeTab: nav.homeTab || 'today', dayPreset: '' }
}

/** Выбор вкладки в таб-баре: под-страница закрывается, возврат обнуляется. */
export function selectTab(nav, id) {
  return { tab: id, subView: '', homeTab: id, dayPreset: '' }
}
