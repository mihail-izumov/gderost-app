// ПРАВИЛО ПРИОРИТЕТА СОСТОЯНИЙ — чистыми функциями, отдельно от разметки.
//
// ⚠ Это правило уровня всего приложения, а не одного экрана. Формулировка
// Михаила, 19.08.2026:
//
//        ДОЛГ ВАЖНЕЕ РЕЗУЛЬТАТА, РЕЗУЛЬТАТ ВАЖНЕЕ ВРЕМЕНИ.
//
// У любого объекта, у которого есть состояние — неделя, день, месяц, ступень, —
// на экране ОДНА метка, и она говорит самое важное из того, что про этот
// объект сейчас правда. Порядок разбора всегда один:
//
//   1. ДОЛГ — чего не хватает, чтобы числу можно было верить. Жёлтый.
//      Пока долг есть, всё остальное про этот объект второстепенно: результат,
//      посчитанный на неполных данных, — половина результата, выданная за целое.
//   2. РЕЗУЛЬТАТ — как объект отработал против плана. Светофор.
//      Законен только там, где данные полны: иначе см. пункт 1.
//   3. ВРЕМЯ — идёт объект, прошёл или ещё впереди. Цвет действия или серый.
//      Самое слабое сообщение: время идёт само и от человека не зависит.
//
// И второе правило, неотделимое от первого:
//
//        ОДНО СОСТОЯНИЕ — ОДИН ЦВЕТ.
//
// Все средства, которыми объект показан в строке (метка, полоса, заливка),
// красятся цветом одного и того же состояния. Расхождение между ними —
// дефект: зелёная полоса под жёлтой меткой заставляет человека решать,
// какому знаку верить, и он перестаёт верить обоим.
//
// Откуда правило. В сводке недель одновременно жили синяя метка «идёт»,
// жёлтая «нет 2 дн» и зелёная полоса под ними — три ответа на разные вопросы
// в одной строке. Человек видел зелёное и жёлтое рядом и не понимал, хорошо
// у него или плохо.

export const BADGE_PRIORITY = ['debt', 'result', 'time']

/**
 * Какое из состояний объекта показывать. Возвращает `'debt' | 'result' |
 * 'time'` — то, о чём метка обязана говорить.
 *
 * @param {{ debt:boolean, result:boolean }} has — что про объект известно:
 *   есть ли долг данных и есть ли законный результат (данные полны).
 */
export function pickState({ debt = false, result = false } = {}) {
  if (debt) return 'debt'
  if (result) return 'result'
  return 'time'
}

/**
 * Цвет состояния. Одно состояние — один цвет: и метка, и полоса берут его
 * отсюда, а не считают каждый по-своему.
 *
 * @param {string} kind — `'debt' | 'result' | 'time'`
 * @param {string} sig — класс светофора для результата: good | warn | bad | idle
 * @param {string} time — `'past' | 'now' | 'ahead' | 'locked'`
 */
export function stateInk(kind, sig = 'idle', time = 'now') {
  if (kind === 'debt') return { bg: 'var(--warning)', ink: 'var(--accent-ink)' }
  if (kind === 'result') {
    if (sig === 'good') return { bg: 'var(--positive)', ink: 'var(--ink-on-color)' }
    if (sig === 'warn') return { bg: 'var(--warning)', ink: 'var(--accent-ink)' }
    if (sig === 'bad') return { bg: 'var(--negative)', ink: 'var(--ink-on-color)' }
    return { bg: 'var(--text)', ink: 'var(--ink-on-color)' }
  }
  if (time === 'now') return { bg: 'var(--action)', ink: 'var(--action-ink)' }
  return { bg: 'var(--surface-2)', ink: 'var(--text-muted)' }
}
