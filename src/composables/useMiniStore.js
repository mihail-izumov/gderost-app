        '   допущением. Раздел «Чего в этих данных нет» перечисляет их поимённо.',
        '',
        '## Как считается',
        '',
        'Метод: **факт → прогноз ≤ план ≤ цель**. План — обязательство владельца,',
        'цель — то, ради чего стараются сверх него. Это разные числа, и подменять',
        'одно другим нельзя.',
        '',
        'Статусы, которые нельзя путать между собой:',
        '',
        '- **со слов** — владелец ввёл сам: план, цель, выручка дня, стартовая сумма;',
        '- **посчитано** — выведено из введённого: план дня, прогноз, «надо» на день;',
        '- **допущение** — приложение приняло за владельца без его данных: веса дней',
        '  недели, пока они не пересчитаны по его же выручке;',
        '- **разнесено** — стартовая сумма, разложенная по дням своего периода.',
        '  Это раскладка, а не замер: такие дни фактом не считаются и оценки не имеют;',
