        '',
        'Правила расчёта:',
        '',
        '- план дня = план месяца × вес дня недели ÷ сумма весов всех дней месяца;',
        '  сумма планов всех дней равна плану месяца ровно;',
        '- темп = вся закрытая выручка ÷ сумма весов закрытых дней. У стартовой суммы',
        '  нет разбивки по дням, но веса её дней известны, поэтому она участвует',
