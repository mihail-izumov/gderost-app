// Куда именно человек шёл, открывая другой экран.
//
// ⚠ Переход между разделами до этого работал так: экран подменялся и вставал
// в самое начало. Человек, нажавший «нужен рекордный темп» на «Сигналах»,
// попадал в «Контроль Дня» и искал глазами то, ради чего пришёл, — а оно
// иногда лежало ниже трёх экранов прокрутки и вдобавок было свёрнуто.
// Переход, после которого надо искать, — это половина перехода.
//
// Здесь лежит адрес назначения: имя блока (`anchor`) и, если речь о неделе,
// её номер (`week`). Оболочка после смены экрана находит `[data-anchor]`
// и подводит к нему прокрутку; экран, у которого блоки свёрнуты, раскрывает
// нужный сам — он один знает, чем они свёрнуты.
//
// Синглтон, а не проп: адрес ставит один экран, читают его оболочка
// и другой экран, и передавать его цепочкой через три компонента значило бы
// заводить проп в каждом.

import { ref } from 'vue'

const target = ref(null)

/** Поставить адрес перехода: { anchor?: string, week?: number, day?: string }. */
export function setNavTarget(t) {
  target.value = t && (t.anchor || t.week || t.day) ? { ...t } : null
}

/** Прочитать и сразу забыть: адрес одноразовый. Второй заход на тот же
 *  экран обычным путём не должен утаскивать человека к прошлому блоку. */
export function takeNavTarget() {
  const t = target.value
  target.value = null
  return t
}

/** Подсмотреть, не забирая: нужно экрану, который решает, что раскрыть. */
export function peekNavTarget() {
  return target.value
}
