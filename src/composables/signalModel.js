// Сигнал Трека — планка сегодняшнего дня, собранная из модели месяца.
//
// Определение перенесено из работающего контура: сигнал — утверждение,
// после которого человек делает что-то сегодня иначе. Планку Трека считает
// честно — сколько надо сегодня, куда идёт месяц, какой недобор. Действия
// и чит-кода в сигнале Трека нет и не будет: их ставит контур на проверенных
// данных, а советы из воздуха здесь запрещены. Эта граница называется
// на экране строкой, а не прячется.
//
// Без данных сигнала нет. Правило оттуда же: не из чего собрать
// утверждение — молчим, а не изображаем сигнал. Пустая карточка с нулями
// была бы шумом, который приучает не читать карточку вовсе.
//
// Модуль чистый: ни Vue, ни DOM, ни хранилища — иначе его нечем проверить
// самопроверкой.

/**
 * Планка дня из модели месяца. Возвращает null, когда сигналу не из чего
 * собраться: модели нет или не внесено ни одного числа.
 *
 * `need` может быть null и при живом сигнале — сегодняшний день уже закрыт
 * или стоит вне месяца; тогда сигнал держится на прогнозе и разрыве.
 */
export function computeTodaySignal(m) {
  if (!m || !(m.realizedCount > 0)) return null

  const landing = m.landing || 0
  const T = m.T || 0
  const d = landing - T
  // Совпадение прогноза с планом направлением не называется — то же правило,
  // что у разрывов в `energyModel`.
  const even = Math.abs(d) < 1

  return {
    need: m.todayNeed ?? null,
    landing,
    planPct: T > 0 ? Math.round((landing / T) * 100) : null,
    gap: even ? 0 : Math.max(0, T - landing),
    surplus: even ? 0 : Math.max(0, landing - T),
    even,
  }
}
