// Энергия роста — посчитанное число, а не шкала настроения.
//
// Правило раздела: у всего здесь есть посчитанное основание. Процент
// складывается из пяти компонент по 20, и каждая компонента отвечает
// на вопрос «на чём стоит это число»: факт со слов стоит слабее факта,
// сверенного чекапом, а прогноз ровным темпом слабее модели на данных.
//
// Верхняя граница бесплатной версии — 20 %, и это факт, а не ограничение:
// всё, что выше, требует данных, которых приложение не собирает, и людей,
// которых в приложении нет. Остаток шкалы человек видит сам — уговаривать
// его нечем и незачем.
//
// Модуль чистый: ни Vue, ни DOM, ни хранилища. Иначе его нечем проверить
// самопроверкой, а число без проверки — обещание, а не расчёт.

