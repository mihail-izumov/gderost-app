/**
 * Этапы подключения. Показываются все и всегда: прогресс из одного шага —
 * это кнопка, а не прогресс, и пункт назначения обязан быть виден с первого дня.
 * `cap` — сколько энергии даёт этап, если пройден целиком.
 *
 * Этапов три, а не четыре (D-113): подписка переехала в собственную вкладку
 * и в лестнице подготовки к буткемпу ей места нет. Второй этап называется
 * «Сессии», а не «Разбор» (D-112): разбор один, сессий после него несколько,
 * и шкала обязана называть то, что человек проходит, а не первый его шаг.
 */
export const LEVELS = [
  { id: 'mini', label: 'Мини', cap: 20, note: 'Считаете сами на своих словах' },
  { id: 'sessions', label: 'Сессии', cap: 70, note: 'Цель, план и прогноз собраны с инженером' },
  { id: 'bootcamp', label: 'Буткемп', cap: 80, note: 'Чекап, план с командой, данные собраны' },
]

/**
 * Что каждый модуль поднимает и до какого уровня. Здесь живёт только логика:
 * названия, цены и состав — в `i18n/energy.js`, потому что это товар, а не расчёт.
 *
 * Сессии разведены по темам (D-103): у каждой карты сущности своя кнопка,
 * и общий модуль `session` не дал бы ответить, что именно поднимет прогноз,
 * а что — план. Формула D-104 при этом не меняется: ступени те же.
 */
export const MODULE_LIFTS = {
  razbor: { goal: PART },
  'session-goal': { goal: PART },
  'session-forecast': { forecast: PART },
  'session-plan': { plan: 10 },
  'session-drivers': { plan: 10 },
  bootcamp: { fact: PART, plan: PART },
  runscale: { live: PART },
}

/**
 * Посчитать энергию на состоянии и модели месяца.
 *
 * Компонента засчитывается, когда она существует: факта нет, пока нет ни одной
 * внесённой выручки, прогноза нет, пока нечего экстраполировать, цели нет,
 * пока она не поставлена. Ставить 5 % за пустое поле значило бы мерить
 * намерение, а не состояние.
 */
export function computeEnergy(set = {}, m = null) {
  const has = {
    fact: !!(set.carry || (Array.isArray(set.days) && set.days.length > 0)),
    forecast: !!(m && m.realizedCount > 0),
    plan: Number(set.month_target) > 0,
    goal: Number(set.month_goal) > 0,
    live: false,
  }

  const parts = PARTS.map((p) => {
    const on = !!has[p.key]
    const value = on ? p.steps[0].pct : 0
    // Следующая ступень — первая, которая выше текущего значения. Она же
    // называет модуль: «что даёт» без «чем открывается» — упрёк.
    const next = p.steps.find((s) => s.pct > value) || null
    return {
      key: p.key,
      label: p.label,
      why: p.why,
      on,
      value,
      max: PART,
      status: on ? p.steps[0].label : 'нет',
      nextLabel: next ? next.label : '',
      nextBy: next ? next.by : '',
      nextGain: next ? next.pct - value : 0,
    }
  })

  const pct = parts.reduce((a, p) => a + p.value, 0)
  const level = LEVELS.reduce((acc, l) => (pct >= l.cap ? l : acc), LEVELS[0])
  return { pct, max: FULL, parts, level }
}

/** Прирост модуля в процентах на конкретном состоянии: «Мощность +15 %». */
export function moduleGain(moduleId, energy) {
  const lifts = MODULE_LIFTS[moduleId]
  if (!lifts || !energy) return 0
  return Object.entries(lifts).reduce((sum, [key, to]) => {
    const part = energy.parts.find((p) => p.key === key)
    if (!part) return sum
    return sum + Math.max(0, to - part.value)
  }, 0)
}

/**
 * Разрывы между сущностями — то, ради чего лестница вообще нарисована.
 *
 * Каждый разрыв назван своим словом и посчитан на числах владельца.
 * Отношение к ним у всех разное, и это предмет разбора, а не подписи
 * на экране: приложение показывает величину и молчит.
 */
export function computeGaps(m) {
  if (!m) return []
  const out = [
    {
      key: 'fact-forecast',
      label: 'осталось заработать по прогнозу',
      value: Math.max(0, (m.landing || 0) - (m.realizedRev || 0)),
      tone: 'neutral',
    },
    // Ровно совпавшие прогноз и план — не «выше» и не «ниже». Округлять
    // совпадение в чью-то пользу значит называть направление там, где его нет.
    (() => {
      const d = (m.landing || 0) - (m.T || 0)
      const same = Math.abs(d) < 1
      return {
        key: 'forecast-plan',
        label: same ? 'прогноз сходится с планом' : (d < 0 ? 'прогноз ниже плана' : 'прогноз выше плана'),
        value: same ? 0 : Math.abs(d),
        tone: same ? 'neutral' : (d < 0 ? 'bad' : 'good'),
      }
    })(),
  ]
  if (m.goal) {
    out.push({
      key: 'plan-goal',
      label: 'цель выше плана',
      value: Math.max(0, m.goal - (m.T || 0)),
      tone: 'neutral',
    })
  }
  return out
}
