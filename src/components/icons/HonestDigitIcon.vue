<script setup>
import { computed } from 'vue'

// Знак «Честная цифра»: сердце в кольце из четырёх дуг — петля роста
// «данные → сигнал → действие → замер». Горит столько дуг, сколько шагов
// петли набрано; порядок по часовой стрелке от двенадцати.
//
// Сердце — из файла Михаила (`feardigit-icon.svg`), контур не тронут.
// Кольцо построено кодом: в присланном файле дуг три, а шагов у петли
// четыре, и сорок градусов дуги руками не перерезать без перерисовки.
// Геометрия кольца снята с исходника — радиус 449..540, зазор 12°, —
// чтобы знак остался тем же на глаз.
//
// Сердце монохромное: состояние несут дуги, и красить им обе части знака
// значит сказать одно дважды.

const props = defineProps({
  // Четыре шага петли: [{ on: Boolean }, ...] по часовой от двенадцати.
  segs: { type: Array, required: true },
  // Цвет горящей дуги.
  tone: { type: String, default: 'var(--warning)' },
  // Цвет погасшей дуги.
  idle: { type: String, default: 'var(--line)' },
  // Цвет сердца.
  ink: { type: String, default: 'var(--text)' },
  // Указка для сторис: номер дуги, о которой идёт речь. Когда задана,
  // состояние человека не показывается — горит только названная дуга
  // цветом `tone`, остальные гаснут. Это режим объяснения, не состояния.
  highlight: { type: Number, default: null },
})

const HEART = [
  'M6718.34,590.194L6860.5,590.194L6887.61,532.521L6932.37,606.384L6983.12,405.481L7031.13,661.096L7099.37,484.573L7157.03,589.595L7367.28,589.529C7436.27,472.674 7382.65,314.297 7243.6,283.953L7243.6,283.943C7156.96,265.567 7094.88,313.334 7043.68,361.714C6982.26,301.354 6903.81,262.745 6817.07,293.329C6691.06,331.874 6657.34,484.915 6718.34,590.194Z',
  'M66.744,56.291L61.098,46.052L49.497,75.858L43.195,45.031L38.229,64.308L30.395,51.138L28.258,56.294L7.343,56.336C17.527,72.106 34.312,82.977 50.038,92.918C65.527,83.543 82.718,71.996 92.605,56.336L66.744,56.291Z',
]

// Дуга кольца: угол от двенадцати по часовой, центр 540, срединный радиус
// и толщина сняты с присланного файла (кольцо занимало 449..540 из 540).
const R = 494.5
const W = 91
const pt = (a) => {
  const r = (a * Math.PI) / 180
  return `${(540 + R * Math.sin(r)).toFixed(1)},${(540 - R * Math.cos(r)).toFixed(1)}`
}
// Четыре дуги по 78° с зазорами 12°, первая начинается сразу после
// зазора на двенадцати.
const ARCS = [0, 90, 180, 270].map((base) => {
  const a1 = base + 6
  const a2 = base + 84
  return `M${pt(a1)}A${R},${R} 0 0 1 ${pt(a2)}`
})

const arcColor = computed(() => (i) => {
  if (props.highlight != null) return i === props.highlight ? props.tone : props.idle
  return props.segs[i] && props.segs[i].on ? props.tone : props.idle
})
</script>

<template>
  <svg viewBox="0 0 1080 1080" aria-hidden="true"
       style="fill-rule:evenodd;clip-rule:evenodd;">
    <path
      v-for="(d, i) in ARCS"
      :key="`arc-${i}`"
      :d="d"
      fill="none"
      :stroke="arcColor(i)"
      :stroke-width="W"
    />
    <g transform="matrix(1,0,0,1,-6503.04,0)">
      <g transform="matrix(0.18288,0,0,0.0257578,6503.04,0)">
        <g transform="matrix(5.46807,0,0,38.8232,-35559.1,0)">
          <path :d="HEART[0]" :fill="ink" style="fill-rule:nonzero;" />
        </g>
        <g transform="matrix(38.7406,0,0,275.058,1015.72,8919.85)">
          <path :d="HEART[1]" :fill="ink" style="fill-rule:nonzero;" />
        </g>
      </g>
    </g>
  </svg>
</template>
